/** Kiểm tra chuỗi icon có phải là URL / file ảnh tải lên không */
export function isImageIcon(icon) {
  if (typeof icon !== "string") return false;
  const s = icon.trim();
  return s.startsWith("http://") || s.startsWith("https://") || s.startsWith("data:") || s.startsWith("/");
}

/** Render icon: hiển thị thẻ <img> nếu là ảnh upload, hoặc emoji/text thông thường */
export function renderIcon(icon, fallback = "📁", style = {}) {
  if (!icon) return fallback;
  if (isImageIcon(icon)) {
    return (
      // eslint-disable-next-line @next/next/no-img-element
      <img
        src={icon}
        alt="icon"
        style={{
          width: "100%",
          height: "100%",
          objectFit: "contain",
          borderRadius: "inherit",
          display: "block",
          ...style,
        }}
      />
    );
  }
  return icon;
}
