/** Phân tích chuỗi icon để nhận diện Iconify (từ URL API hoặc format 'prefix:name') */
export function parseIconify(str) {
  if (typeof str !== "string") return null;
  const s = str.trim();
  // Khớp URL: https://api.iconify.design/{prefix}/{name}.svg?color=%23...
  const urlMatch = s.match(/api\.iconify\.design\/([^/?#]+)\/([^/?#.]+)\.svg(?:\?.*color=([^&#]+))?/i);
  if (urlMatch) {
    const prefix = urlMatch[1];
    const name = urlMatch[2];
    const color = urlMatch[3] ? decodeURIComponent(urlMatch[3]) : "";
    return { name: `${prefix}:${name}`, color };
  }
  // Khớp định dạng: 'prefix:name' (ví dụ 'lucide:phone', 'simple-icons:zalo', 'ri:facebook-fill')
  if (/^[a-z0-9-]+:[a-z0-9-]+$/i.test(s)) {
    return { name: s, color: "" };
  }
  return null;
}

/** Kiểm tra chuỗi icon có phải là URL / CDN SVG / file ảnh / Iconify icon không */
export function isImageIcon(icon) {
  if (typeof icon !== "string") return false;
  const s = icon.trim();
  if (parseIconify(s)) return true;
  return (
    s.startsWith("http://") ||
    s.startsWith("https://") ||
    s.startsWith("data:") ||
    s.startsWith("/")
  );
}

/** Chuyển đổi mã icon của Iconify (vd 'lucide:phone') thành CDN SVG URL */
export function iconifyToUrl(iconName, color = "") {
  if (!iconName) return "";
  const cleaned = iconName.replace(":", "/");
  const base = `https://api.iconify.design/${cleaned}.svg`;
  return color ? `${base}?color=${encodeURIComponent(color)}` : base;
}

/** Render icon: hiển thị vector Iconify (tự động batch, cache và không bị rate limit), thẻ <img> nếu là ảnh upload, hoặc emoji/text */
export function renderIcon(icon, fallback = "📁", style = {}) {
  if (!icon) return fallback;

  // 1. Iconify Vector (URL api.iconify.design hoặc chuỗi prefix:name)
  const parsed = parseIconify(icon);
  if (parsed) {
    const iconColor = style.color || parsed.color || undefined;
    const size = style.width || style.height || "1.25em";
    return (
      <iconify-icon
        icon={parsed.name}
        style={{
          fontSize: size,
          width: size,
          height: size,
          display: "inline-flex",
          alignItems: "center",
          justifyContent: "center",
          verticalAlign: "middle",
          flexShrink: 0,
          color: iconColor,
          ...style,
        }}
      />
    );
  }

  // 2. URL ảnh tải từ máy tính hoặc link thông thường
  if (isImageIcon(icon)) {
    return (
      // eslint-disable-next-line @next/next/no-img-element
      <img
        src={icon}
        alt="icon"
        loading="lazy"
        style={{
          width: style.width || "1.25em",
          height: style.height || "1.25em",
          maxWidth: "100%",
          maxHeight: "100%",
          objectFit: "contain",
          verticalAlign: "middle",
          display: "inline-block",
          ...style,
        }}
        onError={(e) => {
          e.currentTarget.style.opacity = "0.3";
        }}
      />
    );
  }

  // 3. Emoji hoặc ký tự thông thường
  return icon;
}
